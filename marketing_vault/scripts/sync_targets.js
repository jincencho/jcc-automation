const fs = require('fs');
const path = require('path');

const TARGETS_FILE = path.join(__dirname, '../../data/viral_targets.json');
const VAULT_TARGETS_DIR = path.join(__dirname, '../Targets');

if (!fs.existsSync(VAULT_TARGETS_DIR)) fs.mkdirSync(VAULT_TARGETS_DIR, { recursive: true });

function sync() {
    const targets = JSON.parse(fs.readFileSync(TARGETS_FILE, 'utf8'));
    console.log(`🔄 Syncing ${targets.length} targets to Obsidian vault...`);

    targets.forEach(target => {
        const fileName = `${target.name.replace(/[\\/:*?"<>|]/g, '_')}.md`;
        const filePath = path.join(VAULT_TARGETS_DIR, fileName);

        const content = `---
id: ${target.id}
region: ${target.region}
name: ${target.name}
move_in_date: ${target.move_in_date}
scheduled_date: ${target.scheduled_date}
status: ${target.status}
tags:
  - target
  - ${target.region.replace(' ', '')}
---

# ${target.name}

## 📍 위치 정보
- **지역**: ${target.region}
- **입주 예정일**: ${target.move_in_date}

## 📅 마케팅 일정
- **발행 예정일**: ${target.scheduled_date}
- **현재 상태**: ${target.status === 'active' ? '🟢 진행 중' : '⚪ 대기'}

## 📝 마케팅 히스토리
\`\`\`dataview
list from "Manuscripts"
where target = [[${target.name}]]
\`\`\`

---
*Generated by JCC Automation Engine*
`;

        fs.writeFileSync(filePath, content);
    });

    console.log('✅ Sync completed.');
}

sync();
